#!/usr/bin/env python3
"""Bundle the cached tool data in /data into site/data_cache.js.

The game is a static site that must also open from file://, where fetch() of
local JSON is blocked, so cached JSON is wrapped as `window.CACHE = {...}`.

Usage:  python3 scripts/build_data.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "site" / "data_cache.js"

FILES = {
    "intel": DATA / "intel" / "quarters.json",
    "signals": DATA / "signals.json",
    "trade": DATA / "trade" / "trade.json",
    "live": DATA / "live.json",
    "counterparties": DATA / "counterparties.json",
    "prices": DATA / "prices" / "anchors.json",
    "responses": DATA / "responses.json",
}


def main() -> None:
    cache = {}
    for key, path in FILES.items():
        if path.exists():
            cache[key] = json.loads(path.read_text())
            print(f"  ✓ {key:15s} {path.relative_to(ROOT)}")
        else:
            print(f"  – {key:15s} missing ({path.relative_to(ROOT)}), game falls back to built-in data")
    # v4 supply networks: data/network/<mineral>.json
    nets = {}
    for path in sorted((DATA / "network").glob("*.json")):
        nets[path.stem] = json.loads(path.read_text())
        print(f"  ✓ network/{path.stem:8s} {path.relative_to(ROOT)}")
    if nets:
        cache["network"] = nets
    body = json.dumps(cache, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text(
        "/* GENERATED by scripts/build_data.py from /data — do not edit by hand. */\n"
        f"window.CACHE = {body};\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
